function t(key, vars) {
  const lang = (typeof state !== "undefined" && state.uiLang) || "de";
  let str = (UI_STRINGS[lang] && UI_STRINGS[lang][key]) || UI_STRINGS.de[key] || key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      str = str.split(`{${k}}`).join(vars[k]);
    });
  }
  return str;
}
